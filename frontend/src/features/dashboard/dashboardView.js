// Pure view helpers for the store dashboard (S4-03). Kept free of React so they can be unit-tested.

/** Acceptance criterion: dashboard data must be refreshed within one minute. */
export const REFRESH_INTERVAL_MS = 60_000

const SOURCE_LABELS = { LLM: 'AI (LLM)', CACHE: 'Bộ nhớ đệm', RULE: 'Luật dự phòng' }
const VIETNAM_TZ = 'Asia/Ho_Chi_Minh'
const ONE_DAY_MS = 86_400_000
const VIETNAM_UTC_OFFSET_MS = 7 * 3_600_000

/** Use the project's business timezone, not UTC or the user's system timezone. */
export function todayInVietnam(now = new Date()) {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: VIETNAM_TZ,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(now)
  const values = Object.fromEntries(parts.map(({ type, value }) => [type, value]))
  return `${values.year}-${values.month}-${values.day}`
}

/** Strictly convert a calendar date in Vietnam to the corresponding UTC midnight instant. */
function vietnamDayStart(day) {
  if (typeof day !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(day)) return null
  const instant = Date.parse(`${day}T00:00:00+07:00`)
  if (!Number.isFinite(instant)) return null
  // Reject impossible calendar dates, which some JS implementations normalize silently.
  const roundTrip = new Date(instant + VIETNAM_UTC_OFFSET_MS).toISOString().slice(0, 10)
  return roundTrip === day ? instant : null
}

/** Inclusive date-input bounds map to [from, to) UTC instants for the backend. */
export function dashboardUtcRange(fromDay, toDay) {
  const from = vietnamDayStart(fromDay)
  const toDayStart = vietnamDayStart(toDay)
  if (from == null || toDayStart == null || from > toDayStart) return null
  return {
    from: new Date(from).toISOString(),
    to: new Date(toDayStart + ONE_DAY_MS).toISOString(),
  }
}

/** Normalises the ai_effectiveness block. Zero sales or older APIs show N/A. */
export function aiEffectivenessView(data) {
  const ai = data?.ai_effectiveness
  const hasSales = Boolean(ai) && ai.attributed_item_count > 0
  const share = ai?.revenue_share_percent
  return {
    state: ai?.state ?? 'N/A',
    hasSales,
    orders: ai?.attributed_order_count ?? 0,
    items: ai?.attributed_item_count ?? 0,
    revenue: ai?.attributed_revenue ?? 0,
    shareLabel: share == null ? 'N/A' : `${share}%`,
    sources: Object.entries(SOURCE_LABELS).map(([key, label]) => ({
      key,
      label,
      count: ai?.source_breakdown?.[key] ?? 0,
    })),
    acceptanceLabel: data?.ai_acceptance_rate == null ? 'N/A' : `${data.ai_acceptance_rate}%`,
  }
}

/** Seconds since the data was generated by the backend; null if timestamp is invalid. */
export function dataAgeSeconds(generatedAt, now = Date.now()) {
  const time = Date.parse(generatedAt)
  return Number.isNaN(time) ? null : Math.max(0, Math.round((now - time) / 1000))
}
